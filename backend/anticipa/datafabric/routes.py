def _resident_out(r: Resident, version: str, as_of: date) -> dict[str, Any]:
    age = age_on(r.birth_date, as_of)
    return {
        "id": r.id, "dataset_version": version, "source_patient_id": r.source_patient_id, "birth_date": r.birth_date,
        "age": age, "age_band": age_band(age), "administrative_sex": r.administrative_sex,
        "preferred_language": r.preferred_language, "district_code": r.district_code, "deceased_date": r.deceased_date,
        "synthetic_status": r.synthetic_status, "age_as_of": as_of, "storage_profile": profile_of(r.source_version),
    }  # fmt: skip


