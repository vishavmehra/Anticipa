# The overview group-bys scan the whole residents table (seconds at 1M rows) and the data changes slowly while a run is
# loading, so it is cached per process for a minute. ponytail: per-process dict; use a shared cache if the API scales out.
OVERVIEW_TTL_S = 60.0
_OVERVIEW_CACHE: dict[tuple, tuple[float, Any]] = {}
ResidentsUser = Annotated[CurrentUser, Depends(require_permission(RESIDENTS_VIEW))]
RecordsUser = Annotated[CurrentUser, Depends(require_permission(RECORDS_VIEW))]
