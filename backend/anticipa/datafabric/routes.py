SYNTHETIC_NOTICE = "Synthetic data: generated by Synthea and a seeded linker; no real person is represented."
AGE_BANDS: tuple[tuple[str, int, int | None], ...] = (
    ("0-17", 0, 17), ("18-29", 18, 29), ("30-39", 30, 39), ("40-49", 40, 49),
    ("50-59", 50, 59), ("60-69", 60, 69), ("70-79", 70, 79), ("80+", 80, None),
)  # fmt: skip
AGE_BAND_RE = "^(" + "|".join(b[0].replace("+", r"\+") for b in AGE_BANDS) + ")$"
CATEGORY_OF_RESOURCE = {
    "Condition": "condition", "Procedure": "procedure", "Observation": "observation", "Immunization": "immunization",
    "MedicationRequest": "medication", "DiagnosticReport": "diagnostic_report", "Encounter": "encounter",
    "DocumentReference": "document_reference",
}  # fmt: skip


# --------------------------------------------------------------------------------------------- helpers
def _years_before(d: date, years: int) -> date:
    try:
        return d.replace(year=d.year - years)
    except ValueError:  # 29 February
        return d.replace(year=d.year - years, day=28)


def age_on(birth: date | None, as_of: date) -> int | None:
    if birth is None:
        return None
    return as_of.year - birth.year - ((as_of.month, as_of.day) < (birth.month, birth.day))


def age_band(age: int | None) -> str | None:
    if age is None:
        return None
    return next(label for label, lo, hi in AGE_BANDS if age >= lo and (hi is None or age <= hi))


def band_birth_range(label: str, as_of: date) -> tuple[date | None, date]:
    """Inclusive (earliest, latest) birth dates of residents aged in the band on `as_of` (earliest None = unbounded)."""
    _, lo, hi = next(b for b in AGE_BANDS if b[0] == label)
    latest = _years_before(as_of, lo)
    earliest = None if hi is None else _years_before(as_of, hi + 1) + timedelta(days=1)
    return earliest, latest


def _as_of(ds: Dataset) -> date:
    ref = ((ds.manifest or {}).get("generation") or {}).get("reference_date")
    return date(int(ref[:4]), int(ref[4:6]), int(ref[6:])) if ref else date.today()


def _latest_dataset(session, version: str | None) -> Dataset | None:
    stmt = select(Dataset).order_by(Dataset.created_at.desc())
    if version:
        stmt = stmt.where(Dataset.dataset_version == version)
    return session.execute(stmt.limit(1)).scalar_one_or_none()


def _resident_or_404(session, resident_id: uuid.UUID) -> tuple[Resident, Dataset]:
    row = session.execute(
        select(Resident, Dataset)
        .join(Dataset, Dataset.id == Resident.dataset_id)
        .where(Resident.id == resident_id)
    ).first()
    if row is None:
        raise NotFound("Resident not found.")
    return row[0], row[1]


