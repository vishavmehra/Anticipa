const glanceRows = (o: PopulationOverview | undefined) =>
  (o?.metrics ?? []).flatMap((m) => {
    const g = GLANCE[m.key];
    return g && !(g.hideIfZero && !m.value) ? [{ key: m.key, label: g.label, hint: g.hint, value: m.value }] : [];
  });
const unavailable = (what: string) => <p className="py-8 text-center text-ink-muted">{what} is not available for your role.</p>;

/** Seats and utilisation, from GET /analytics/capacity. Only mounted for roles that hold capacity.view. */
