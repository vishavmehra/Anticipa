/** Outreach counts, from GET /analytics/engagement (delivery and booking outcomes are simulated by design). */
function useEngagement() {
  return useApi("pop-engagement", (signal) => api<EngagementOverview>("/analytics/engagement", { signal }));
}

function OutreachCard({ compact = false }: { compact?: boolean }) {
  const res = useEngagement();
  const e = res.data?.data;
  const responded = e && e.communications.total ? e.responses.total / e.communications.total : null;
  return (
    <Card as="section" aria-labelledby="pop-outreach">
      <CardHeader id="pop-outreach" icon="megaphone" title="Outreach and engagement" aside={<DataLabel kind="simulated" />} />
      <div className="px-5 pb-5">
        {res.error ? (
          unavailable("Outreach")
        ) : !e ? (
          <div className="skeleton h-28 w-full" role="status" aria-label="Loading outreach" />
        ) : (
          <div className={compact ? "grid grid-cols-1 gap-3 [&>*]:min-w-0" : "grid grid-cols-3 gap-3 text-center [&>*]:min-w-0"}>
            {[
              [fmtInt(e.communications.total), "Messages sent"],
              [responded == null ? "None" : fmtPct(responded), "Response rate"],
              [fmtInt(e.appointments.total), "Appointments booked"],
            ].map(([v, label], i) => (
              <div key={label} className={compact ? "flex items-baseline justify-between gap-3 border-b border-line pb-2 last:border-0" : i === 1 ? "border-line border-x px-2" : ""}>
                <p className={`tnum font-display font-bold ${compact ? "order-2 text-2xl" : "text-3xl"}`}>{v}</p>
                <p className="text-ink-muted">{label}</p>
              </div>
            ))}
          </div>
        )}
      </div>
    </Card>
  );
}

/** Identify, plan, engage, attend, complete: one real count per step. */
function LoopClosure({ identified, planned, closed }: { identified: number | null | undefined; planned: number | null; closed: number | null | undefined }) {
  const can = useCan();
  const res = useEngagement();
  const f = res.data?.data.funnel;
  const steps: { label: string; icon: IconName; value: number | null | undefined; simulated?: boolean }[] = [
    { label: "Identify", icon: "target", value: identified },
    { label: "Plan", icon: "calendar", value: planned },
    { label: "Engage", icon: "megaphone", value: f?.cases_contacted, simulated: true },
    { label: "Attend", icon: "calendar-check", value: f?.cases_attended, simulated: true },
    { label: "Complete", icon: "check-circle", value: closed },
  ];
  return (
    <Card as="section" aria-labelledby="pop-loop" className="mb-5">
      <CardHeader id="pop-loop" icon="refresh" title="Loop closure" subtitle="From identification to completed preventive care, counted in cases" />
      <ol className="grid grid-cols-2 gap-x-4 gap-y-5 px-5 pb-5 sm:grid-cols-5">
        {steps.map((s, i) => {
          const hidden = s.simulated && (!can("engagement.view") || !!res.error);
          return (
            <li key={s.label} className="relative text-center">
              {i > 0 && <span aria-hidden="true" className="absolute top-5 right-1/2 hidden h-px w-full bg-brand-light sm:block" />}
              <span className="relative mx-auto grid size-10 place-items-center icon-tile">
                <Icon name={s.icon} className="size-5" />
              </span>
              <p className="mt-2 font-medium text-ink-soft">{s.label}</p>
              <p className="tnum font-display text-xl font-bold">{hidden ? "Not available" : s.value === undefined && s.simulated && !f ? "…" : fmtInt(s.value ?? null)}</p>
              {s.simulated && !hidden && <DataLabel kind="simulated" />}
            </li>
          );
        })}
      </ol>
    </Card>
  );
}

