export type IconName = keyof typeof ICONS;

// Closed-shape icons take the soft tint fill (the duotone look). Open-path glyphs (chevrons, arrows, check, plus) stay line only,
// because filling an open path draws a stray triangle.
const TINTED = new Set<IconName>([
  "bell", "building", "calendar", "calendar-check", "clipboard", "clipboard-check", "clock", "database", "droplet", "eye", "file", "flag", "flask",
  "gauge", "hand-heart", "heart", "care", "hourglass", "info", "alert", "check-circle", "x-circle", "layers", "lock", "mail", "pin", "megaphone", "message",
  "plug", "ribbon", "scroll", "server", "settings", "shield", "shield-alert", "target", "warning", "user", "user-check", "users", "users-round", "home",
  "pie", "grid", "insight", "map", "bookmark", "hexagon", "theme-light", "theme-dark", "theme-clinical", "dashboard", "cpu", "zap", "syringe", "stethoscope", "sparkles", "key",
] as IconName[]);

/** Decorative duotone icon (aria-hidden): 1.8 stroke, round caps, soft tint on closed shapes. Pair it with visible text. */
export function Icon({ name, className = "size-5", strokeWidth = 1.8 }: { name: IconName; className?: string; strokeWidth?: number }) {
  const C = ICONS[name];
  const tint = TINTED.has(name);
  return <C aria-hidden="true" className={`shrink-0 ${className}`} strokeWidth={strokeWidth} fill={tint ? "currentColor" : "none"} fillOpacity={tint ? 0.16 : undefined} />;
}

export type TileTone = "brand" | "ok" | "warn" | "danger" | "info" | "teal" | "rose" | "blue" | "amber" | "green" | "neutral";

/** An icon in a soft glass tile: hairline white edge, pale tint ramp, a whisper of shadow. The one tile style for the whole app. */
export function IconTile({ name, size = "md", tone = "brand" }: { name: IconName; size?: "sm" | "md" | "lg"; tone?: TileTone }) {
  const box = { sm: "size-8", md: "size-11", lg: "size-14" }[size];
  const glyph = { sm: "size-4", md: "size-[1.3rem]", lg: "size-7" }[size];
  return (
    <span aria-hidden="true" className={`icon-tile ${tone === "brand" ? "" : `icon-tile-${tone}`} ${box}`}>
      <Icon name={name} className={glyph} />
    </span>
  );
}
